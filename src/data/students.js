const FRESH_IMPORT_TIMESTAMP = '2026-05-11T08:00:00Z'

// Helper to build a default record. Captures the "fresh import" defaults in
// one place so adding a mock student stays consistent.
function freshStudent(fields) {
  const hasStart = !!fields.class_start_date
  return {
    contact_method: null,
    contact_result: null,
    expected_payment_amount: null,
    expected_payment_date: null,
    forecast_confidence: null,
    forecast_notes: '',
    invoice_number: '',
    last_contact_date: null,
    last_updated_at: FRESH_IMPORT_TIMESTAMP,
    last_updated_by: 'CSV Import',
    lifecycle_status: hasStart
      ? 'Start Date Confirmed'
      : 'Agency Approved / Need to Confirm Start Date',
    next_follow_up_date: null,
    notes: '',
    start_date_status: hasStart ? 'Tentative' : 'Not Set',
    ...fields,
  }
}

